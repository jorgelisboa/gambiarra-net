export const statsFromRow = (row: Row) =>
  Object.fromEntries(STAT_KEYS.map((k, i) => [k, row[i]])) as Stats;

/** Linha `face` (1–10) do template do role. */
export const templateRow = (role: Role, face: number) =>
  statsFromRow(STAT_TEMPLATES[role][face - 1]);

/** Streetrat: 1d10 escolhe a linha inteira. */
export function rollStreetrat(role: Role) {
  const face = d10();
  return { face, stats: templateRow(role, face) };
}

/** Edgerunner: 1d10 por stat, cada um lido na sua coluna. */
export function rollEdgerunner(role: Role) {
  const faces = STAT_KEYS.map(() => d10());
  const stats = Object.fromEntries(
    STAT_KEYS.map((k, i) => [k, STAT_TEMPLATES[role][faces[i] - 1][i]]),
  ) as Stats;
  return { faces, stats };
}
